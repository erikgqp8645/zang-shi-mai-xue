/**
 * 算出哪些步骤／关口被点亮。
 *
 * 规则：传入的 route 集合里有该步骤的任一路线，即点亮。
 * 点亮只表示「现有依脉用方规则在这一步有命中」，**不是**「该用这个方」。
 */
export function litStepIds(hitRoutes: Iterable<string>): Set<string> {
  const routes = new Set(hitRoutes)
  const lit = new Set<string>()
  for (const p of FLOW_PATHS) {
    for (const s of p.steps) {
      if (s.routes.some((r) => routes.has(r))) lit.add(s.id)
    }
  }
  for (const s of TRIAD_STEPS) {
    if (s.routes.some((r) => routes.has(r))) lit.add(s.id)
  }
  for (const g of BLOCK_GATES) {
    if (g.routes.some((r) => routes.has(r))) lit.add(g.id)
  }
  return lit
}

/** 关口 id（供命中定位用） */
export const BLOCK_GATE_IDS = BLOCK_GATES.map((g) => g.id)
